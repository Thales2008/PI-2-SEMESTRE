CREATE DATABASE IF NOT EXISTS savi_mare_sociale
  CHARACTER SET utf8mb4
  COLLATE utf8mb4_unicode_ci;

USE savi_mare_sociale;

CREATE TABLE IF NOT EXISTS users (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(150) NOT NULL,
  username VARCHAR(50) NULL UNIQUE,
  email VARCHAR(190) NOT NULL UNIQUE,
  phone VARCHAR(30) NULL,
  password_hash VARCHAR(255) NOT NULL,
  role ENUM('admin', 'customer') NOT NULL DEFAULT 'customer',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS categories (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(100) NOT NULL UNIQUE,
  slug VARCHAR(120) NOT NULL UNIQUE,
  description VARCHAR(255) NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS products (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  category_id BIGINT UNSIGNED NOT NULL,
  name VARCHAR(180) NOT NULL,
  slug VARCHAR(200) NOT NULL UNIQUE,
  color_name VARCHAR(80) NOT NULL,
  color_group ENUM('Neutras', 'Verdes', 'Rosas', 'Azuis', 'Marrons', 'Outras cores') NOT NULL DEFAULT 'Outras cores',
  description TEXT NULL,
  price DECIMAL(10, 2) NOT NULL DEFAULT 18.13,
  old_price DECIMAL(10, 2) NULL DEFAULT 25.90,
  discount_percent TINYINT UNSIGNED NOT NULL DEFAULT 30,
  rating DECIMAL(2, 1) NOT NULL DEFAULT 5.0,
  sold_count INT UNSIGNED NOT NULL DEFAULT 0,
  image VARCHAR(255) NOT NULL,
  purchase_url VARCHAR(255) NULL,
  is_best_seller TINYINT(1) NOT NULL DEFAULT 0,
  best_seller_label VARCHAR(40) NULL,
  active TINYINT(1) NOT NULL DEFAULT 1,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_products_category
    FOREIGN KEY (category_id) REFERENCES categories(id)
    ON UPDATE CASCADE
    ON DELETE RESTRICT
) ENGINE=InnoDB;